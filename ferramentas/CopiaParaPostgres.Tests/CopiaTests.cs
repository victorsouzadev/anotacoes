using CopiaParaPostgres;
using Microsoft.Data.Sqlite;
using Npgsql;
using Xunit;

namespace CopiaParaPostgres.Tests;

public class ConversaoTests
{
    [Theory]
    [InlineData(1L, "boolean", true)]
    [InlineData(0L, "boolean", false)]
    [InlineData("12.5", "numeric", 12.5)]
    [InlineData(7L, "integer", 7)]
    public void Converte_pelo_tipo_de_destino(object v, string tipo, object esperado) =>
        Assert.Equal(Convert.ToString(esperado, System.Globalization.CultureInfo.InvariantCulture),
            Convert.ToString(Copia.Converter(v, tipo, "t", "c"), System.Globalization.CultureInfo.InvariantCulture));

    [Fact]
    public void Data_do_ef_sem_fuso_vira_utc()
    {
        var d = (DateTime)Copia.Converter("2026-11-21 13:45:10.1234567", "timestamp with time zone", "t", "c");
        Assert.Equal(DateTimeKind.Utc, d.Kind);
        Assert.Equal(new DateTime(2026, 11, 21, 13, 45, 10, DateTimeKind.Utc).AddTicks(1234567), d);
    }

    [Fact]
    public void Data_com_fuso_e_convertida()
    {
        var d = (DateTime)Copia.Converter("2026-11-21T10:00:00-03:00", "timestamp with time zone", "t", "c");
        Assert.Equal(13, d.Hour);
    }

    [Fact]
    public void Valor_que_nao_cabe_diz_tabela_e_coluna()
    {
        var e = Assert.Throws<InvalidOperationException>(() => Copia.Converter("abc", "numeric", "fin_contas", "Saldo"));
        Assert.Contains("fin_contas.Saldo", e.Message);
    }
}

/// <summary>Cópia de ponta a ponta num Postgres de verdade (só com <c>HUB_PG_TESTE</c>, como na CI).</summary>
public sealed class CopiaPostgresTests : IDisposable
{
    private static readonly string? Base = Environment.GetEnvironmentVariable("HUB_PG_TESTE");
    private readonly string _banco = $"copia_{Guid.NewGuid():N}";
    private readonly string _sqlite = Path.Combine(Path.GetTempPath(), $"copia_{Guid.NewGuid():N}.db");
    private string Destino => new NpgsqlConnectionStringBuilder(Base) { Database = _banco, Pooling = false }.ConnectionString;

    public CopiaPostgresTests()
    {
        if (string.IsNullOrEmpty(Base)) return;
        Pg(Base, $"CREATE DATABASE \"{_banco}\"");
        Pg(Destino, """
            CREATE SCHEMA nucleo; CREATE SCHEMA financas;
            CREATE TABLE nucleo.users ("Id" text PRIMARY KEY, "Email" text NOT NULL, "CreatedAt" timestamptz NOT NULL);
            CREATE TABLE financas.fin_contas ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "UserId" text NOT NULL REFERENCES nucleo.users("Id"), "Saldo" numeric NOT NULL, "Ativa" boolean NOT NULL,
                "Nova" text NOT NULL DEFAULT '');
            """);
        Sqlite("""
            CREATE TABLE fin_contas (Id INTEGER PRIMARY KEY, UserId TEXT NOT NULL, Saldo TEXT NOT NULL, Ativa INTEGER NOT NULL);
            INSERT INTO fin_contas VALUES (1, 'u1', '10.25', 1), (5, 'u1', '-3', 0);
            CREATE TABLE users (Id TEXT PRIMARY KEY, Email TEXT NOT NULL, CreatedAt TEXT NOT NULL);
            INSERT INTO users VALUES ('u1', 'a@b', '2026-01-02 03:04:05');
            CREATE TABLE "__EFMigrationsHistory_financas" (MigrationId TEXT);
            """);
    }

    [SkippableFact]
    public void Copia_cada_tabela_para_o_schema_do_dono_e_confere()
    {
        Skip.If(string.IsNullOrEmpty(Base), "HUB_PG_TESTE não definida");
        var r = Copia.Executar(_sqlite, Destino, limpar: false, TextWriter.Null);
        Assert.Equal(["financas.fin_contas", "nucleo.users"], r.Tabelas.Select(t => $"{t.Schema}.{t.Tabela}"));
        Assert.Equal(12.25m, Escalar("SELECT sum(\"Saldo\") FROM financas.fin_contas"));
        Assert.Equal(1L, Escalar("SELECT count(*) FROM financas.fin_contas WHERE \"Ativa\""));
        // A sequência continua depois do maior Id copiado.
        Pg(Destino, "INSERT INTO financas.fin_contas (\"UserId\", \"Saldo\", \"Ativa\") VALUES ('u1', 0, true)");
        Assert.Equal(6, Escalar("SELECT max(\"Id\") FROM financas.fin_contas"));
    }

    [SkippableFact]
    public void Tabela_sem_destino_falha_sem_gravar_nada()
    {
        Skip.If(string.IsNullOrEmpty(Base), "HUB_PG_TESTE não definida");
        Sqlite("CREATE TABLE orfa (Id TEXT)");
        Assert.Throws<InvalidOperationException>(() => Copia.Executar(_sqlite, Destino, false, TextWriter.Null));
        Assert.Equal(0L, Escalar("SELECT count(*) FROM nucleo.users"));
    }

    [SkippableFact]
    public void Destino_com_linhas_so_e_limpo_com_a_opcao()
    {
        Skip.If(string.IsNullOrEmpty(Base), "HUB_PG_TESTE não definida");
        Pg(Destino, "INSERT INTO nucleo.users VALUES ('x', 'x@x', now())");
        Assert.Throws<InvalidOperationException>(() => Copia.Executar(_sqlite, Destino, false, TextWriter.Null));
        Copia.Executar(_sqlite, Destino, limpar: true, TextWriter.Null);
        Assert.Equal(1L, Escalar("SELECT count(*) FROM nucleo.users WHERE \"Id\" = 'u1'"));
        Assert.Equal(1L, Escalar("SELECT count(*) FROM nucleo.users"));
    }

    private object? Escalar(string sql)
    {
        using var c = new NpgsqlConnection(Destino);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        return cmd.ExecuteScalar();
    }

    private static void Pg(string cs, string sql)
    {
        using var c = new NpgsqlConnection(cs);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        cmd.ExecuteNonQuery();
    }

    private void Sqlite(string sql)
    {
        using var c = new SqliteConnection($"Data Source={_sqlite};Pooling=False");
        c.Open();
        using var cmd = c.CreateCommand();
        cmd.CommandText = sql;
        cmd.ExecuteNonQuery();
    }

    public void Dispose()
    {
        if (!string.IsNullOrEmpty(Base)) Pg(Base, $"DROP DATABASE IF EXISTS \"{_banco}\" WITH (FORCE)");
        if (File.Exists(_sqlite)) File.Delete(_sqlite);
    }
}
